#!/usr/bin/env python3
"""Write modules/ladder/tables.inc from reference.py: the voice's tables have one source.

    python3 modules/ladder/gen_tables.py          # write
    python3 modules/ladder/gen_tables.py --check  # exit 1 when tables.inc is stale
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import reference as R  # noqa: E402


def longs(name, vals):
    out = [f"{name}:"]
    for i in range(0, len(vals), 8):
        out.append("        .long   " + ",".join(str(v) for v in vals[i:i + 8]))
    return out


def text():
    L = ["| GENERATED by modules/ladder/gen_tables.py from reference.py -- do not edit.",
         f"        .set    INC_MAX, {R.INC_MAX}", f"        .set    FC_LOW, {R.FC_LOW}",
         f"        .set    FC_TOP, {R.FC_TOP}", f"        .set    DC_A31, {R.DC_A31}",
         f"        .set    THIRD, {R.THIRD}", "        .even"]
    L += longs("INC", R.INC)
    L += longs("DET_Q8", R.DET_Q8)
    L += longs("GLIDE_C", R.GLIDE_C)
    L += longs("ATK_STEP", R.ATK_STEP)
    L += longs("DEC_C", R.DEC_C)
    L += longs("SUS_L", R.SUS_L)
    L += longs("G_TAB", R.G_TAB)
    L += longs("CUT_I", R.CUT_I)
    L += longs("CONT_I", R.CONT_I)
    L += longs("K8", R.K8)
    L += longs("COMP4", R.COMP4)
    L += longs("MIX15", R.MIX15)
    L += longs("NZ", R.NZ)
    L += longs("TANH", R.TANH)
    L += longs("SEMI256", [256 * R.semis(k) for k in range(128)])
    L += longs("WAVE_OF", [R.wave(k) for k in range(128)])
    L += longs("PW_TAB", list(R.PW))
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    p = HERE / "tables.inc"
    if "--check" in sys.argv:
        ok = p.exists() and p.read_text() == text()
        print("tables.inc " + ("current" if ok else "STALE: python3 modules/ladder/gen_tables.py"))
        sys.exit(0 if ok else 1)
    p.write_text(text())
    print(f"wrote {p}")
