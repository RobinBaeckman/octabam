#!/usr/bin/env python3
"""Write modules/grainer/tables.inc from reference.py: the voice's tables have one source.

    python3 modules/grainer/gen_tables.py          # write
    python3 modules/grainer/gen_tables.py --check  # exit 1 when tables.inc is stale
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import reference as R  # noqa: E402


def longs(name, vals):
    out = [f"{name}:"]
    for i in range(0, len(vals), 8):
        out.append("        .long   " + ",".join(str(v) for v in vals[i:i + 8]))
    return out


def text():
    L = ["| GENERATED by modules/grainer/gen_tables.py from reference.py -- do not edit.",
         f"        .set    EDGE, {R.EDGE}", f"        .set    NSLOTS, {R.SLOTS}", "        .even"]
    for name in ("SIZE_N", "GMAX", "MODE_OF", "SYNC_SH", "CH", "RATE", "SCAN_Q", "POS_Q", "SPRD_Q",
                 "PAN_Q", "GAIN16", "SQ"):
        L += longs(name, getattr(R, name))
    L += longs("TS", R.TS_TABLE)          # stock's own copy is at 0x80004000; ours keeps the voice self-contained
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    p = HERE / "tables.inc"
    if "--check" in sys.argv:
        ok = p.exists() and p.read_text() == text()
        print("tables.inc " + ("current" if ok else "STALE: python3 modules/grainer/gen_tables.py"))
        sys.exit(0 if ok else 1)
    p.write_text(text())
    print(f"wrote {p}")
