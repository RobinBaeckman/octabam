#!/usr/bin/env python3
"""Write modules/poly/tables.inc from reference.py: the voice's tables have one source.

    python3 modules/poly/gen_tables.py          # write
    python3 modules/poly/gen_tables.py --check  # exit 1 when tables.inc is stale
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import reference as R  # noqa: E402


def longs(name, vals):
    out = [f"{name}:"]
    for i in range(0, len(vals), 8):
        out.append("        .long   " + ",".join(str(v) for v in vals[i:i + 8]))
    return out


def text():
    L = ["| GENERATED by modules/poly/gen_tables.py from reference.py -- do not edit."]
    for name in ("INC_MAX", "FC_LOW", "FC_MAX", "ENV_FLOOR", "DC_A", "SHELF", "CLIP_G", "NZ_A", "NZ_C"):
        v = getattr(R, name, None)
        L.append(f"        .set    {name}, {v if v is not None else getattr(R.L, name)}")
    L.append("        .even")
    L += longs("INC", R.L.INC)
    L += longs("TANH", R.L.TANH)
    L += longs("G_TAB", R.G_TAB[:R.FC_MAX + 1])
    for name in ("KS", "ATK_STEP", "DEC_C", "SUS_L", "CUT_I", "ENV_I", "K8", "COMP4", "PW", "SUB_L",
                 "HPF_A", "NOISE_L"):
        L += longs(name, list(getattr(R, name)))
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    p = HERE / "tables.inc"
    if "--check" in sys.argv:
        ok = p.exists() and p.read_text() == text()
        print("tables.inc " + ("current" if ok else "STALE: python3 modules/poly/gen_tables.py"))
        sys.exit(0 if ok else 1)
    p.write_text(text())
    print(f"wrote {p}")
